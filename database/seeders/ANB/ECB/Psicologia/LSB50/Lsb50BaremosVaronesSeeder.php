    private function guardar(
        PsicoTest $test,
        string $codigo,
        array $datos
    ): void
    {
        $dimension = PsicoDimension::where(
            'test_id',
            $test->id
        )
        ->where(
            'codigo',
            $codigo
        )
        ->firstOrFail();

        foreach($datos as $fila){

            DB::table('ECB_psico_baremos')->updateOrInsert(

                [

                    'dimension_id'=>$dimension->id,

                    'sexo'=>'M',

                    'desde'=>$fila[0],

                    'hasta'=>$fila[1],

                ],

                [

                    'percentil'=>$fila[2],

                    'edad_desde'=>null,

                    'edad_hasta'=>null,

                    'interpretacion'=>null,

                    'created_at'=>now(),

                    'updated_at'=>now(),

                ]

            );

        }

    }

